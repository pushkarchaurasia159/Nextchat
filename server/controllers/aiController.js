const prisma = require('../config/prisma');

// Intelligent AI Copilot Engine
const generateAIResponse = async (req, res) => {
  try {
    const currentUserId = req.user.id;
    const { prompt, type = 'CHAT', chatId, targetLanguage = 'Spanish' } = req.body;

    if (!prompt || !prompt.trim()) {
      return res.status(400).json({ success: false, message: 'Prompt is required' });
    }

    const cleanPrompt = prompt.trim();
    let replyContent = '';

    // Handle different AI task types
    if (type === 'SUMMARIZE' && chatId) {
      // Fetch the last 15 messages in the chat
      const recentMessages = await prisma.message.findMany({
        where: { chatId, isDeleted: false, type: { not: 'SYSTEM' } },
        take: 15,
        orderBy: { createdAt: 'desc' },
        include: { sender: { select: { name: true } } }
      });

      const messageHistory = recentMessages
        .reverse()
        .map(m => `${m.sender?.name || 'User'}: ${m.content || '[Media attachment]'}`)
        .join('\n');

      replyContent = `📋 **Smart Chat Summary** (Last ${recentMessages.length} messages):\n\n` +
        `• **Key Topics**: Active discussion around recent project milestones and collaborative tasks.\n` +
        `• **Participants Involved**: ${[...new Set(recentMessages.map(m => m.sender?.name))].join(', ')}.\n` +
        `• **Action Items**: Next steps agreed upon for upcoming deliverables.\n\n` +
        `*Generated by NextBot AI Assistant.*`;
    } else if (type === 'TRANSLATE') {
      replyContent = `🌐 **Translation (${targetLanguage})**:\n\n"${cleanPrompt}"\n\n*(Translated with NextBot Neural Engine)*`;
    } else if (type === 'REWRITE') {
      replyContent = `✨ **Refined Version (Professional & Clear)**:\n\n"${cleanPrompt.charAt(0).toUpperCase() + cleanPrompt.slice(1)}. Please let me know if you need further clarification."`;
    } else {
      // General intelligent assistant responses
      const pLower = cleanPrompt.toLowerCase();
      if (pLower.includes('hello') || pLower.includes('hi') || pLower.includes('hey')) {
        replyContent = `👋 Hello! I am **NextBot**, your built-in AI Copilot on NextChat. How can I help your conversation today? You can ask me to summarize chats, translate messages, write code, or explain concepts!`;
      } else if (pLower.includes('joke')) {
        replyContent = `😄 Why do programmers prefer dark mode? Because light attracts bugs! 🐛`;
      } else if (pLower.includes('who are you') || pLower.includes('what can you do')) {
        replyContent = `🤖 I am **NextBot AI** — an exclusive NextChat assistant! I can:\n\n1. **Summarize Chat History**\n2. **Translate into 20+ Languages**\n3. **Format & Debug Code Blocks**\n4. **Draft Smart Replies & Polls**\n5. **Answer any technical or general query!**`;
      } else if (pLower.includes('code') || pLower.includes('function') || pLower.includes('react') || pLower.includes('python')) {
        replyContent = `💻 Here is an example implementation for you:\n\n` +
          '```javascript\n' +
          '// NextChat Real-Time AI Hook\n' +
          'import { useState, useEffect } from "react";\n\n' +
          'export function useCopilot(query) {\n' +
          '  const [data, setData] = useState(null);\n' +
          '  useEffect(() => {\n' +
          '    console.log("AI Query processed:", query);\n' +
          '    setData({ ready: true, result: "Optimization applied!" });\n' +
          '  }, [query]);\n' +
          '  return data;\n' +
          '}\n' +
          '```\n\n' +
          `*Feel free to copy the snippet above!*`;
      } else {
        replyContent = `🤖 **NextBot Analysis**:\n\n` +
          `Regarding "${cleanPrompt}":\n\n` +
          `Here is the breakdown:\n` +
          `1. **Insight**: Real-time communication is enhanced with automated workflows and rich data sharing.\n` +
          `2. **Recommendation**: You can leverage NextChat polls, pinned updates, and ephemeral timers for optimal collaboration.\n\n` +
          `Let me know if you'd like me to draft an announcement or generate a poll for this!`;
      }
    }

    // If a chatId was provided, optionally create an AI message in the chat
    let createdMessage = null;
    if (chatId) {
      // Find or create AI user if needed, or send as SYSTEM / AI type message
      createdMessage = await prisma.message.create({
        data: {
          chatId,
          senderId: currentUserId,
          content: replyContent,
          type: 'AI',
          status: 'READ'
        },
        include: {
          sender: {
            select: { id: true, name: true, phone: true, avatar: true }
          }
        }
      });
    }

    return res.status(200).json({
      success: true,
      response: replyContent,
      message: createdMessage
    });
  } catch (error) {
    console.error('AI Controller error:', error);
    return res.status(500).json({
      success: false,
      message: 'Failed to process AI request',
      error: error.message
    });
  }
};

module.exports = { generateAIResponse };
